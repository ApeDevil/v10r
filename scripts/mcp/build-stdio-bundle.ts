/**
 * Build (or verify) the self-contained stdio server bundle, `mcp/server.bundle.js`.
 *
 * The stdio server runs in an ephemeral `oven/bun` container from a read-only repo mount with no
 * network and no `node_modules`. The official SDK it now speaks through is a dependency, so the
 * server is shipped the way any dependency-carrying program is: bundled. `bun build` inlines the SDK
 * (and its zod / ajv) into one minified ES module; nothing is installed or fetched at runtime.
 *
 *   bun run mcp:bundle:build     # regenerate the bundle (commit the result)
 *   bun run mcp:bundle:check     # fail if the committed bundle is stale (wired into the gate)
 *
 * The bundle's first line is its provenance: an **input digest** (sha256 over every file the
 * build read — repo sources AND the bundled node_modules files, by path and content, plus each
 * bundled package's name@version), the **Bun version** that built it, and the **output digest** of
 * the code below the line. `--check` (in `bun run validate`) fails when:
 *  - the inputs moved — a source edit, a dependency bump, or a patched/tampered node_modules file
 *    under an unchanged version number;
 *  - the committed code no longer matches its recorded output digest — a hand edit of the bundle;
 *  - the checking Bun is the recording Bun and a fresh build differs byte for byte — the build is
 *    not reproducible, or the committed file is not what this tree builds.
 * A different Bun may emit different bytes for the same inputs, so across Bun versions the check
 * rests on the two digests rather than a byte compare.
 *
 * The bundle is built from `stdio-server.ts` and started by `server.ts`, the entry every client
 * registration names. It lives beside both on purpose: `import.meta.dir` resolves the same directory in
 * both, so the registry (read from disk at startup, never inlined) is found from either.
 */
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { relative, resolve } from 'node:path';

const ROOT = resolve(import.meta.dir, '../..');
const ENTRY = resolve(ROOT, 'mcp/stdio-server.ts');
const BUNDLE_PATH = resolve(ROOT, 'mcp/server.bundle.js');
const HEADER_PREFIX = '// v10r-patterns stdio bundle — generated by scripts/mcp/build-stdio-bundle.ts —';
const HEADER_PATTERN = /^inputs sha256:([0-9a-f]{64}) · bun ([^ ]+) · output sha256:([0-9a-f]{64})$/;

interface Built {
	code: string;
	body: string;
	digest: string;
	inputs: string[];
	packages: string[];
}

/** `name@version` of the package a node_modules path belongs to. */
function packageOf(path: string): string | null {
	const match = /node_modules\/((?:@[^/]+\/)?[^/]+)\//.exec(path);
	if (!match) return null;
	const name = match[1];
	const manifest = JSON.parse(readFileSync(resolve(ROOT, 'node_modules', name, 'package.json'), 'utf8')) as {
		version: string;
	};
	return `${name}@${manifest.version}`;
}

async function build(): Promise<Built> {
	const loaded = new Set<string>();
	const result = await Bun.build({
		entrypoints: [ENTRY],
		target: 'bun',
		format: 'esm',
		minify: true,
		plugins: [
			{
				name: 'record-inputs',
				setup(builder) {
					builder.onLoad({ filter: /.*/ }, (args) => {
						loaded.add(args.path);
						return undefined;
					});
				},
			},
		],
	});
	if (!result.success) {
		throw new Error(`bun build failed:\n${result.logs.map(String).join('\n')}`);
	}
	const inputs = [...loaded]
		.filter((path) => !path.includes('/node_modules/'))
		.map((path) => relative(ROOT, path))
		.sort();
	// node_modules files by their path inside node_modules, so a different checkout location or
	// a symlinked node_modules hashes the same.
	const dependencyFiles = [...loaded]
		.filter((path) => path.includes('/node_modules/'))
		.map((path) => ({ path, key: path.slice(path.lastIndexOf('/node_modules/') + 1) }))
		.sort((a, b) => a.key.localeCompare(b.key));
	const packages = [...new Set([...loaded].map(packageOf).filter((name): name is string => name !== null))].sort();
	const hash = createHash('sha256');
	for (const input of inputs) {
		hash.update(`${input}\0`);
		hash.update(readFileSync(resolve(ROOT, input)));
		hash.update('\0');
	}
	for (const file of dependencyFiles) {
		hash.update(`${file.key}\0`);
		hash.update(readFileSync(file.path));
		hash.update('\0');
	}
	for (const pkg of packages) hash.update(`${pkg}\0`);
	const digest = hash.digest('hex');
	const body = await result.outputs[0].text();
	const code = `${HEADER_PREFIX} inputs sha256:${digest} · bun ${Bun.version} · output sha256:${sha256(body)}\n${body}`;
	return { code, body, digest, inputs, packages };
}

function sha256(text: string): string {
	return createHash('sha256').update(text).digest('hex');
}

interface Committed {
	digest: string;
	bunVersion: string;
	outputDigest: string;
	body: string;
	code: string;
}

function readCommitted(): Committed | null {
	let code: string;
	try {
		code = readFileSync(BUNDLE_PATH, 'utf8');
	} catch {
		return null;
	}
	const newline = code.indexOf('\n');
	const firstLine = newline === -1 ? code : code.slice(0, newline);
	if (!firstLine.startsWith(HEADER_PREFIX)) return null;
	const match = HEADER_PATTERN.exec(firstLine.slice(HEADER_PREFIX.length).trim());
	if (!match) return null;
	return { digest: match[1], bunVersion: match[2], outputDigest: match[3], body: code.slice(newline + 1), code };
}

function fail(reason: string): never {
	console.error(`mcp/server.bundle.js: ${reason}\nRun \`bun run mcp:bundle:build\` and commit the result.`);
	process.exit(1);
}

const built = await build();
if (process.argv.includes('--check')) {
	const committed = readCommitted();
	if (committed === null) fail('missing, or its provenance header is unreadable.');
	if (committed.digest !== built.digest) {
		fail(`stale — committed inputs ${committed.digest}, this tree's inputs ${built.digest}.`);
	}
	if (sha256(committed.body) !== committed.outputDigest) {
		fail('the code does not match its recorded output digest — the bundle was edited by hand.');
	}
	const sameBun = committed.bunVersion === Bun.version;
	if (sameBun && built.code !== committed.code) {
		fail(`a fresh build with the recording Bun (${Bun.version}) differs byte for byte from the committed file.`);
	}
	console.log(
		`mcp/server.bundle.js is current (${built.inputs.length} repo inputs, ${built.packages.join(', ')}; ` +
			(sameBun
				? `byte-identical rebuild on bun ${Bun.version}).`
				: `built on bun ${committed.bunVersion}, checked by digest on bun ${Bun.version}).`),
	);
} else {
	writeFileSync(BUNDLE_PATH, built.code);
	console.log(
		`wrote mcp/server.bundle.js — ${(built.code.length / 1024).toFixed(0)} KB, ${built.inputs.length} repo inputs, ${built.packages.join(', ')}, bun ${Bun.version}`,
	);
}
