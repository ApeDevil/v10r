/**
 * Build (or verify) the MCP Apps Views the hosted MCP serves as `ui://` resources.
 *
 * A View is one self-contained HTML document — its script, its styles and the v10r design tokens
 * it uses all inline — because a host renders it in a sandboxed iframe whose CSP admits no
 * network origin. It is NOT part of the SvelteKit client bundle: its sources sit under
 * `src/lib/server/mcp/apps/view/` (Kit refuses a client import of `server/`), `bun build` compiles
 * them on their own, and the server imports the finished document as a string.
 *
 *   bun run mcp:apps:build     # regenerate every View (commit the result)
 *   bun run mcp:apps:check     # fail if a committed View is stale (wired into the gate)
 *
 * Tokens come from `src/app.css`, the one source of color: every `var(--…)` the View's sheet
 * names is looked up in the `:root` (light) and `.dark` blocks, together with the tokens those
 * values reference in turn, and inlined as `:root` and `:root[data-theme="dark"]` (the attribute
 * the official `applyDocumentTheme` sets from the host's theme). A name app.css does not define —
 * the host's standard MCP Apps variables — is left to the host.
 *
 * Provenance follows `build-stdio-bundle.ts`: the first line records an input digest (every file
 * the build read, repo and node_modules, plus package versions), the Bun version and an output
 * digest; `--check` fails on moved inputs, a hand edit, or — on the recording Bun — any byte of
 * difference from a fresh build.
 */
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { relative, resolve } from 'node:path';

const ROOT = resolve(import.meta.dir, '../..');
const APP_CSS = resolve(ROOT, 'src/app.css');

interface ViewSource {
	/** Output, relative to the repo root. */
	out: string;
	entry: string;
	sheet: string;
	title: string;
}

const VIEWS: ViewSource[] = [
	{
		out: 'src/lib/server/mcp/apps/pattern-explorer.view.html',
		entry: 'src/lib/server/mcp/apps/view/pattern-explorer.ts',
		sheet: 'src/lib/server/mcp/apps/view/pattern-explorer.css',
		title: 'v10r pattern explorer',
	},
	{
		out: 'src/lib/server/mcp/apps/model-viewer.view.html',
		entry: 'src/lib/server/mcp/apps/view/model-viewer.ts',
		sheet: 'src/lib/server/mcp/apps/view/model-viewer.css',
		title: 'v10r 3D viewer',
	},
];

/**
 * Defence in depth beside the host's sandbox: the document refuses every network fetch, frame,
 * form and base change itself, so even a host that skipped the declared CSP renders it offline.
 * Inline script and style are what a single-file View is made of.
 */
const DOCUMENT_CSP =
	"default-src 'none'; script-src 'unsafe-inline'; style-src 'unsafe-inline'; img-src data:; font-src data:; connect-src 'none'; frame-src 'none'; object-src 'none'; base-uri 'none'; form-action 'none'";

const HEADER_PREFIX = '<!-- v10r MCP Apps View — generated by scripts/mcp/build-app-views.ts —';
const HEADER_PATTERN = /^inputs sha256:([0-9a-f]{64}) · bun ([^ ]+) · output sha256:([0-9a-f]{64}) -->$/;

/** The declarations of one top-level block (`:root {` / `.dark {`) of app.css, by name. */
function tokenBlock(css: string, selector: string): Map<string, string> {
	const start = css.indexOf(`\n${selector} {`);
	if (start === -1) throw new Error(`src/app.css has no top-level "${selector} {" block`);
	const end = css.indexOf('\n}', start);
	const block = css.slice(start, end).replace(/\/\*[\s\S]*?\*\//g, '');
	const tokens = new Map<string, string>();
	for (const match of block.matchAll(/(--[a-z0-9-]+)\s*:\s*([^;]+);/g)) {
		tokens.set(match[1], match[2].replace(/\s+/g, ' ').trim());
	}
	return tokens;
}

const varNames = (text: string) => [...text.matchAll(/var\(\s*(--[a-z0-9-]+)/g)].map((match) => match[1]);

/** The tokens `sheet` needs from `defined`, closed over the tokens their values reference. */
function neededTokens(sheet: string, light: Map<string, string>, dark: Map<string, string>): string[] {
	const needed = new Set<string>();
	const queue = varNames(sheet);
	while (queue.length > 0) {
		const name = queue.shift();
		if (name === undefined || needed.has(name) || !light.has(name)) continue;
		needed.add(name);
		queue.push(...varNames(light.get(name) ?? ''), ...varNames(dark.get(name) ?? ''));
	}
	return [...needed].sort();
}

function declarations(names: string[], tokens: Map<string, string>): string {
	return names
		.filter((name) => tokens.has(name))
		.map((name) => `${name}:${tokens.get(name)};`)
		.join('');
}

function packageOf(path: string): string | null {
	const match = /node_modules\/((?:@[^/]+\/)?[^/]+)\//.exec(path);
	if (!match) return null;
	const manifest = JSON.parse(readFileSync(resolve(ROOT, 'node_modules', match[1], 'package.json'), 'utf8')) as {
		version: string;
	};
	return `${match[1]}@${manifest.version}`;
}

const sha256 = (text: string | Buffer) => createHash('sha256').update(text).digest('hex');

interface Built {
	out: string;
	document: string;
	body: string;
	digest: string;
	scriptBytes: number;
}

async function build(view: ViewSource): Promise<Built> {
	const loaded = new Set<string>([resolve(ROOT, view.sheet), APP_CSS]);
	const result = await Bun.build({
		entrypoints: [resolve(ROOT, view.entry)],
		target: 'browser',
		format: 'esm',
		minify: true,
		plugins: [
			{
				name: 'record-inputs',
				setup(builder) {
					builder.onLoad({ filter: /.*/ }, (args) => {
						loaded.add(args.path);
						return undefined;
					});
				},
			},
		],
	});
	if (!result.success) throw new Error(`bun build failed:\n${result.logs.map(String).join('\n')}`);
	// `</script` inside a string literal would end the element early; `<\/` is the same string to JS.
	const script = (await result.outputs[0].text()).replaceAll('</script', '<\\/script').trim();

	const css = readFileSync(APP_CSS, 'utf8');
	const sheet = readFileSync(resolve(ROOT, view.sheet), 'utf8');
	const light = tokenBlock(css, ':root');
	const dark = tokenBlock(css, '.dark');
	const names = neededTokens(sheet, light, dark);
	const ownSheet = sheet
		.replace(/\/\*[\s\S]*?\*\//g, '')
		.replace(/\s+/g, ' ')
		.trim();
	const styles = `:root{${declarations(names, light)}}:root[data-theme="dark"]{${declarations(names, dark)}}${ownSheet}`;

	const body = [
		'<!doctype html>',
		'<html lang="en">',
		'<head>',
		'<meta charset="utf-8">',
		`<meta http-equiv="Content-Security-Policy" content="${DOCUMENT_CSP}">`,
		'<meta name="viewport" content="width=device-width, initial-scale=1">',
		`<title>${view.title}</title>`,
		`<style>${styles}</style>`,
		'</head>',
		'<body>',
		'<main id="app"></main>',
		`<script type="module">${script}</script>`,
		'</body>',
		'</html>',
		'',
	].join('\n');

	const repoInputs = [...loaded]
		.filter((path) => !path.includes('/node_modules/'))
		.map((path) => relative(ROOT, path))
		.sort();
	const dependencyFiles = [...loaded]
		.filter((path) => path.includes('/node_modules/'))
		.map((path) => ({ path, key: path.slice(path.lastIndexOf('/node_modules/') + 1) }))
		// Two copies of one package can share a key (nested node_modules): break the tie by full path,
		// or the order would follow Bun's parallel load order and the digest would wander.
		.sort((a, b) => a.key.localeCompare(b.key) || a.path.localeCompare(b.path));
	const packages = [...new Set([...loaded].map(packageOf).filter((name): name is string => name !== null))].sort();
	const hash = createHash('sha256');
	for (const input of repoInputs)
		hash
			.update(`${input}\0`)
			.update(readFileSync(resolve(ROOT, input)))
			.update('\0');
	for (const file of dependencyFiles) hash.update(`${file.key}\0`).update(readFileSync(file.path)).update('\0');
	for (const pkg of packages) hash.update(`${pkg}\0`);
	const digest = hash.digest('hex');
	const document = `${HEADER_PREFIX} inputs sha256:${digest} · bun ${Bun.version} · output sha256:${sha256(body)} -->\n${body}`;
	return { out: view.out, document, body, digest, scriptBytes: script.length };
}

function check(built: Built): string | null {
	let committed: string;
	try {
		committed = readFileSync(resolve(ROOT, built.out), 'utf8');
	} catch {
		return 'missing.';
	}
	const newline = committed.indexOf('\n');
	const firstLine = committed.slice(0, newline);
	const match = firstLine.startsWith(HEADER_PREFIX)
		? HEADER_PATTERN.exec(firstLine.slice(HEADER_PREFIX.length).trim())
		: null;
	if (!match) return 'its provenance header is unreadable.';
	const [, digest, bunVersion, outputDigest] = match;
	if (digest !== built.digest) return `stale — committed inputs ${digest}, this tree's inputs ${built.digest}.`;
	if (sha256(committed.slice(newline + 1)) !== outputDigest) return 'it was edited by hand (output digest mismatch).';
	if (bunVersion === Bun.version && committed !== built.document) {
		return `a fresh build on the recording Bun (${Bun.version}) differs byte for byte.`;
	}
	return null;
}

const checking = process.argv.includes('--check');
let failed = false;
for (const view of VIEWS) {
	const built = await build(view);
	if (checking) {
		const problem = check(built);
		if (problem) {
			console.error(`${built.out}: ${problem}\nRun \`bun run mcp:apps:build\` and commit the result.`);
			failed = true;
		} else {
			console.log(`${built.out} is current.`);
		}
	} else {
		writeFileSync(resolve(ROOT, built.out), built.document);
		const gzipped = Bun.gzipSync(built.document).length;
		console.log(
			`wrote ${built.out} — ${(built.document.length / 1024).toFixed(0)} KB (${(gzipped / 1024).toFixed(0)} KB gzip; script ${(built.scriptBytes / 1024).toFixed(0)} KB), bun ${Bun.version}`,
		);
	}
}
if (failed) process.exit(1);
