#!/usr/bin/env bun
/**
 * Generative UI measurements, written to `scripts/generative-ui/bench-report.json`:
 *
 * 1. Payload tokens per scenario (o200k_base, `gpt-tokenizer`) for four ways to ship the same
 *    UI: the tool-driven baseline (data for a fixed card), A2UI v1.0 JSON, A2UI Express and a
 *    json-render spec (`comparison-payloads.ts`), plus the catalog prompt each A2UI format adds,
 *    and the A2UI payloads of the catalog examples (the newer components' jobs).
 * 2. The adversarial fixtures through the server compiler: every one must end as expected.
 * 3. The renderer bundle: `LazyGenerativeSurface` built with Vite, reporting the eager entry
 *    chunk and the lazy renderer chunk (raw + gzip, per package), and asserting zero lit.
 *
 * Deterministic: no timestamps, sorted keys, so a diff of the report is a diff of the facts.
 *
 *   bun run genui:bench            # writes the report
 *   bun run genui:bench --check    # fails if the report on disk differs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join, relative, resolve } from 'node:path';
import { gzipSync } from 'node:zlib';
import { svelte, vitePreprocess } from '@sveltejs/vite-plugin-svelte';
import { encode } from 'gpt-tokenizer/encoding/o200k_base';
import { build, type Rolldown } from 'vite';
import {
	GENERATIVE_UI_DOMAIN_COMPONENTS,
	GENERATIVE_UI_GENERAL_COMPONENTS,
} from '../../src/lib/generative-ui/catalog.ts';
import {
	ADVERSARIAL_SURFACES,
	GENERATIVE_SURFACE_CATALOG_EXAMPLES,
	GENERATIVE_SURFACE_SCENARIOS,
} from '../../src/lib/generative-ui/fixtures/index.ts';
import { compileGenerativeSurface } from '../../src/lib/server/ai/generative-ui/compile-surface.ts';
import { buildGenerativeSurfacePrompt } from '../../src/lib/server/ai/generative-ui/surface-prompt.ts';
import { a2uiZodDedupe } from '../build/a2ui-zod-dedupe.ts';
import { COMPARISON_PAYLOADS } from './comparison-payloads.ts';

const ROOT = resolve(import.meta.dirname, '../..');
const REPORT = join(import.meta.dirname, 'bench-report.json');

const tokens = (text: string) => encode(text).length;
/** What a model would emit: minified JSON. */
const json = (value: unknown) => JSON.stringify(value);

function payloadTokens() {
	return GENERATIVE_SURFACE_SCENARIOS.map((scenario) => {
		const comparison = COMPARISON_PAYLOADS[scenario.id];
		if (!comparison) throw new Error(`no comparison payloads for ${scenario.id}`);
		const row = (baseline: unknown, a2uiJson: unknown, express: string, jsonRender: unknown) => {
			const counts = {
				baseline: tokens(json(baseline)),
				a2uiJson: tokens(json(a2uiJson)),
				a2uiExpress: tokens(express),
				jsonRender: tokens(json(jsonRender)),
			};
			return {
				...counts,
				expressVsJson: Number((counts.a2uiExpress / counts.a2uiJson).toFixed(2)),
				chars: {
					baseline: json(baseline).length,
					a2uiJson: json(a2uiJson).length,
					a2uiExpress: express.length,
					jsonRender: json(jsonRender).length,
				},
			};
		};
		const surfaceId = (scenario.messages[0] as { createSurface: { surfaceId: string } }).createSurface.surfaceId;
		const compiled = compileGenerativeSurface({ format: 'express', source: scenario.express }, { surfaceId });
		return {
			id: scenario.id,
			expressCompiles: compiled.ok,
			initial: row(comparison.baseline, scenario.messages, scenario.express, comparison.jsonRender),
			...(scenario.followUp && comparison.followUp
				? {
						followUp: row(
							comparison.followUp.baseline,
							scenario.followUp.messages,
							scenario.followUp.express,
							comparison.followUp.jsonRender,
						),
					}
				: {}),
		};
	});
}

/** The catalog examples: no fixed-card baseline exists for them, so only the A2UI forms. */
function exampleTokens() {
	return GENERATIVE_SURFACE_CATALOG_EXAMPLES.map((example) => {
		const surfaceId = (example.messages[0] as { createSurface: { surfaceId: string } }).createSurface.surfaceId;
		const compiled = compileGenerativeSurface({ format: 'express', source: example.express }, { surfaceId });
		const row = (messages: unknown, express: string) => ({
			a2uiJson: tokens(json(messages)),
			a2uiExpress: tokens(express),
		});
		return {
			id: example.id,
			expressCompiles: compiled.ok,
			initial: row(example.messages, example.express),
			...(example.followUp ? { followUp: row(example.followUp.messages, example.followUp.express) } : {}),
		};
	});
}

function promptTokens() {
	return {
		a2uiExpress: tokens(buildGenerativeSurfacePrompt('express')),
		a2uiJson: tokens(buildGenerativeSurfacePrompt('json')),
		components: {
			domain: GENERATIVE_UI_DOMAIN_COMPONENTS.length,
			general: GENERATIVE_UI_GENERAL_COMPONENTS.length,
		},
		note:
			'Catalog prompt for the v10r catalog (general + domain sections), generated by @a2ui/agent. Before the ' +
			'2026-11-24 extension (13 components) it was 2,026 Express / 5,179 JSON tokens. The baseline needs no catalog ' +
			'prompt (one tool schema per fixed card instead); json-render was measured at 3,730 tokens for a 5-component ' +
			'catalog in the research run (not re-measured here).',
	};
}

function adversarialValidation() {
	const results = ADVERSARIAL_SURFACES.map((fixture) => {
		const compiled = compileGenerativeSurface({ format: 'json', source: fixture.messages }, { surfaceId: 'probe' });
		const outcome = compiled.ok ? 'accepted' : 'refused';
		const pass = fixture.expect === 'inert' ? compiled.ok : !compiled.ok;
		return {
			id: fixture.id,
			expect: fixture.expect,
			outcome,
			codes: compiled.ok ? [] : [...new Set(compiled.refusals.map((r) => r.code))].sort(),
			pass,
		};
	});
	return { passed: results.filter((r) => r.pass).length, total: results.length, results };
}

const packageOf = (id: string) => {
	// The last node_modules segment: a nested copy (web_core's own zod) counts as its package.
	const match = id.match(/.*node_modules\/((?:@[^/]+\/)?[^/]+)/);
	if (match) return match[1];
	if (id.includes('/src/lib/')) return `src/lib/${relative(join(ROOT, 'src/lib'), id).split('/')[0]}`;
	return id.startsWith('\0') ? 'bundler runtime (preload helper)' : 'other';
};

/**
 * Packages every route already ships (the Svelte runtime, the headless primitives and the
 * styling helpers), left out so the chunk sizes are what a generative surface *adds*.
 */
const SHARED_WITH_THE_APP = [/^svelte($|\/)/, /^bits-ui($|\/)/, /^class-variance-authority$/, /^clsx$/, /^esm-env$/];

async function bundle() {
	const entry = join(ROOT, 'src/lib/components/composites/generative-surface/LazyGenerativeSurface.svelte');
	const output = (await build({
		configFile: false,
		root: ROOT,
		logLevel: 'silent',
		// The same zod resolution as the app build (`vite.config.ts`), so the figures are the shipped ones.
		plugins: [a2uiZodDedupe(), svelte({ preprocess: vitePreprocess(), emitCss: false })],
		resolve: { alias: [{ find: /^#lib\//, replacement: `${join(ROOT, 'src/lib')}/` }] },
		build: {
			write: false,
			minify: true,
			target: 'es2022',
			modulePreload: false,
			rolldownOptions: {
				input: { surface: entry },
				preserveEntrySignatures: 'strict',
				external: SHARED_WITH_THE_APP,
				output: { format: 'es', entryFileNames: '[name].js', chunkFileNames: '[name].js' },
				treeshake: {
					moduleSideEffects: [
						{ test: /\/src\/lib\/components\/[^?]*\.(svelte|ts|js)$/, external: false, sideEffects: false },
						{ test: /\/src\/lib\/paraglide\/messages(\.js$|\/)/, external: false, sideEffects: false },
					],
				},
			},
		},
	})) as Rolldown.RolldownOutput | Rolldown.RolldownOutput[];
	const chunks = (Array.isArray(output) ? output : [output])
		.flatMap((o) => o.output)
		.filter((c): c is Rolldown.OutputChunk => c.type === 'chunk');

	const describe = (chunk: Rolldown.OutputChunk) => {
		const byPackage = new Map<string, number>();
		for (const [id, info] of Object.entries(chunk.modules)) {
			const pkg = packageOf(id);
			byPackage.set(pkg, (byPackage.get(pkg) ?? 0) + info.renderedLength);
		}
		const packages = Object.fromEntries([...byPackage].filter(([, n]) => n > 0).sort((a, b) => b[1] - a[1]));
		return {
			raw: Buffer.byteLength(chunk.code),
			gzip: gzipSync(chunk.code, { level: 9 }).length,
			packages,
			litBytes: Object.entries(packages)
				.filter(([pkg]) => /^(lit|lit-html|lit-element|@lit\/|@lit-labs\/)/.test(pkg))
				.reduce((sum, [, n]) => sum + n, 0),
			hasWebCore: Object.keys(packages).some((pkg) => pkg.startsWith('@a2ui/')),
		};
	};

	/** Copies of zod 3's core module bundled, one per resolved package directory. */
	const zodV3Copies = new Set(
		chunks.flatMap((c) => Object.keys(c.modules)).filter((id) => /\/zod\/v3\/types\.js$/.test(id)),
	).size;

	const eager = chunks.find((c) => c.isEntry);
	if (!eager) throw new Error('the build produced no entry chunk');
	const lazy = chunks.filter((c) => !c.isEntry);
	const lazyTotal = lazy.map(describe);
	return {
		note:
			'Vite (rolldown) production build of LazyGenerativeSurface, minified, gzip level 9. svelte, bits-ui, ' +
			'class-variance-authority and clsx are external: every route ships them already. CSS not counted. raw/gzip are ' +
			'the emitted (minified) chunks; per-package figures are rendered lengths before minification.',
		eagerEntry: describe(eager),
		zodV3Copies,
		lazyChunks: {
			count: lazy.length,
			raw: lazyTotal.reduce((sum, c) => sum + c.raw, 0),
			gzip: lazyTotal.reduce((sum, c) => sum + c.gzip, 0),
			litBytes: lazyTotal.reduce((sum, c) => sum + c.litBytes, 0),
			hasWebCore: lazyTotal.some((c) => c.hasWebCore),
			packages: Object.fromEntries(
				[...new Set(lazyTotal.flatMap((c) => Object.keys(c.packages)))]
					.map((pkg) => [pkg, lazyTotal.reduce((sum, c) => sum + (c.packages[pkg] ?? 0), 0)] as const)
					.sort((a, b) => b[1] - a[1]),
			),
		},
		reference: {
			jsonRenderCore:
				'@json-render/core tree-shaken (defineCatalog, createSpecStreamCompiler, validateSpec, resolveElementProps): ' +
				'14 KB min / 4.3 KB gzip with zod external — research run, esbuild, not re-measured here.',
		},
	};
}

function sortKeys(value: unknown): unknown {
	if (Array.isArray(value)) return value.map(sortKeys);
	if (value && typeof value === 'object') {
		return Object.fromEntries(
			Object.keys(value)
				.sort()
				.map((key) => [key, sortKeys((value as Record<string, unknown>)[key])]),
		);
	}
	return value;
}

const report = {
	tokenizer: 'gpt-tokenizer o200k_base',
	catalog: '@a2ui/web_core 0.15.0 + @a2ui/agent 0.1.0, v10r catalog v1',
	payloadTokens: payloadTokens(),
	exampleTokens: exampleTokens(),
	promptTokens: promptTokens(),
	adversarialValidation: adversarialValidation(),
	rendererBundle: await bundle(),
};

/** Formatted the way `biome ci` expects, so the committed report passes the gate as written. */
function formatted(value: unknown): string {
	const result = Bun.spawnSync(['bunx', 'biome', 'format', `--stdin-file-path=${REPORT}`], {
		cwd: ROOT,
		stdin: new TextEncoder().encode(JSON.stringify(value, null, '\t')),
	});
	if (result.exitCode !== 0) throw new Error(`biome format failed: ${result.stderr.toString()}`);
	return result.stdout.toString();
}

const text = formatted(sortKeys(report));
if (process.argv.includes('--check')) {
	const onDisk = readFileSync(REPORT, 'utf8');
	if (onDisk !== text) {
		console.error('bench-report.json is stale: run `bun run genui:bench`');
		process.exit(1);
	}
	console.log('bench-report.json is current');
} else {
	writeFileSync(REPORT, text);
	console.log(text);
}

const failed = [
	...report.adversarialValidation.results.filter((r) => !r.pass),
	...[...report.payloadTokens, ...report.exampleTokens].filter((r) => !r.expressCompiles),
];
const bundleProblems = [
	report.rendererBundle.eagerEntry.hasWebCore && 'web_core reached the eager entry chunk',
	report.rendererBundle.lazyChunks.litBytes > 0 && 'lit reached the renderer chunk',
	!report.rendererBundle.lazyChunks.hasWebCore && 'web_core is missing from the lazy chunk',
	report.rendererBundle.zodV3Copies !== 1 && `${report.rendererBundle.zodV3Copies} copies of zod 3 in the renderer`,
].filter(Boolean);
if (failed.length > 0 || bundleProblems.length > 0) {
	console.error('generative UI bench failed:', failed.map((r) => r.id).join(', '), bundleProblems.join('; '));
	process.exit(1);
}
