/**
 * Third-party license file — `/third-party-licenses.txt`, emitted by `vite build`.
 *
 * `/credits` is the curated colophon; this is its exhaustive, generated counterpart: every npm
 * package whose code, styles or fonts end up in the browser build, with its version, declared
 * license and the license/notice text it ships with. MIT, BSD, ISC, Apache and OFL all ask for
 * that text to travel with redistributed copies, and the client bundle is the only part of the
 * app that is redistributed — server-only dependencies run on our host and are deliberately not
 * listed.
 *
 * Source of truth is the client module graph (`getModuleIds()`), not `package.json`, so the file
 * names exactly what was bundled, transitive dependencies included. `?worker` bundles are separate
 * Rollup builds; `workerPlugin()` feeds their graphs into the same collection before the main
 * client build emits. SvelteKit's service-worker build runs without user plugins and imports no
 * npm packages.
 */
import { existsSync, readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import type { Plugin } from 'vite';

/** Emitted at the client output root, hence served at `/third-party-licenses.txt` (linked from `/credits`). */
const FILE_NAME = 'third-party-licenses.txt';

const NODE_MODULES = '/node_modules/';
const LICENSE_FILE = /^(licen[cs]e|copying|notice)([.-][\w.-]*)?$/i;
const RULE = '='.repeat(78);

interface PackageMeta {
	name?: string;
	version?: string;
	license?: unknown;
	licenses?: unknown;
	repository?: unknown;
}

/** `…/node_modules/@scope/pkg/dist/x.js?v=1` → `…/node_modules/@scope/pkg`; null for first-party ids. */
function packageRoot(moduleId: string): string | null {
	const id = moduleId.replace(/^\0/, '').replace(/[?#].*$/, '').replaceAll('\\', '/');
	const at = id.lastIndexOf(NODE_MODULES);
	if (at === -1) return null;
	const [first, second] = id.slice(at + NODE_MODULES.length).split('/');
	if (!first || first.startsWith('.')) return null;
	const name = first.startsWith('@') ? `${first}/${second}` : first;
	return id.slice(0, at + NODE_MODULES.length) + name;
}

/** The SPDX expression `package.json` declares, or null — some packages (runed, svelte-toolbelt) ship a LICENSE file only. */
function declaredLicense(meta: PackageMeta): string | null {
	if (typeof meta.license === 'string') return meta.license;
	const typed = (value: unknown) =>
		typeof value === 'object' && value !== null && 'type' in value ? String(value.type) : null;
	if (typed(meta.license)) return typed(meta.license);
	if (Array.isArray(meta.licenses)) return meta.licenses.map(typed).filter(Boolean).join(' OR ') || null;
	return null;
}

function repositoryUrl(meta: PackageMeta): string | null {
	const raw =
		typeof meta.repository === 'string'
			? meta.repository
			: typeof meta.repository === 'object' && meta.repository !== null && 'url' in meta.repository
				? String(meta.repository.url)
				: null;
	if (!raw) return null;
	if (/^github:|^[\w.-]+\/[\w.-]+$/.test(raw)) return `https://github.com/${raw.replace(/^github:/, '')}`;
	return raw.replace(/^git\+/, '').replace(/^git:\/\//, 'https://').replace(/\.git$/, '');
}

function renderPackage(root: string): { key: string; text: string } | null {
	const metaPath = join(root, 'package.json');
	if (!existsSync(metaPath)) return null;
	const meta = JSON.parse(readFileSync(metaPath, 'utf-8')) as PackageMeta;
	const key = `${meta.name ?? root} ${meta.version ?? ''}`.trim();
	const license = declaredLicense(meta);
	const repository = repositoryUrl(meta);
	const texts = readdirSync(root)
		.filter((file) => LICENSE_FILE.test(file))
		.sort()
		.map((file) => readFileSync(join(root, file), 'utf-8').trim());

	const lines = [RULE, key, `License: ${license ?? 'not declared in package.json — see the license text below'}`];
	if (repository) lines.push(`Repository: ${repository}`);
	lines.push('-'.repeat(78));
	lines.push(
		texts.length > 0
			? texts.join(`\n\n${'- '.repeat(39)}\n\n`)
			: license
				? `The package ships no license file; its package.json declares "${license}".`
				: 'The package ships neither a license file nor a license declaration.',
	);
	return { key, text: lines.join('\n') };
}

function render(roots: Iterable<string>): { count: number; text: string } {
	const byKey = new Map<string, string>();
	for (const root of roots) {
		const entry = renderPackage(root);
		if (entry) byKey.set(entry.key, entry.text);
	}
	const keys = [...byKey.keys()].sort((a, b) => a.localeCompare(b, 'en'));
	const header = [
		'THIRD-PARTY SOFTWARE NOTICES — v10r',
		'',
		'Every npm package whose code, styles or fonts are bundled into the browser build of this',
		'site, with the license it is distributed under and the license text it ships with.',
		'Generated by `vite build` from the client module graph. Server-only dependencies are not',
		'distributed and not listed. The curated colophon, including hosted services and assets,',
		'is /credits.',
		'',
		`${keys.length} packages.`,
	].join('\n');
	return { count: keys.length, text: `${[header, ...keys.map((key) => byKey.get(key))].join('\n\n')}\n` };
}

/** Roots seen in a build's module graph. */
function collectRoots(moduleIds: Iterable<string>, into: Set<string>): void {
	for (const id of moduleIds) {
		const root = packageRoot(id);
		if (root) into.add(root);
	}
}

/**
 * `plugin` goes in `plugins`, `workerPlugin` in `worker.plugins` — they share one collection, and
 * the client build (whose `?worker` imports are bundled before it emits) writes the file.
 */
export function thirdPartyLicenses(): { plugin: Plugin; workerPlugin: () => Plugin } {
	const roots = new Set<string>();

	const plugin: Plugin = {
		name: 'v10r:third-party-licenses',
		configureServer(server) {
			server.middlewares.use(`/${FILE_NAME}`, (_req, res) => {
				res.setHeader('content-type', 'text/plain; charset=utf-8');
				res.end('Generated by `vite build` from the client module graph — run a production build to see it.\n');
			});
		},
		generateBundle() {
			if (this.environment.config.consumer !== 'client') return;
			collectRoots(this.getModuleIds(), roots);
			const { count, text } = render(roots);
			// A client bundle with no npm package in it means the collection broke, not that the app
			// stopped depending on Svelte — fail the build rather than ship an empty notice file.
			if (count === 0) this.error(`${FILE_NAME}: no npm packages found in the client module graph`);
			this.emitFile({ type: 'asset', fileName: FILE_NAME, source: text });
		},
	};

	const workerPlugin = (): Plugin => ({
		name: 'v10r:third-party-licenses:worker',
		generateBundle() {
			collectRoots(this.getModuleIds(), roots);
		},
	});

	return { plugin, workerPlugin };
}
